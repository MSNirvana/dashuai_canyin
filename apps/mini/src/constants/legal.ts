export type LegalDocKey = 'user' | 'privacy'

/** 一个「小标题 + 内容」块，用于隐私政策里的分类罗列 */
export interface LegalBlock {
  title: string
  paragraphs?: string[]
  list?: string[]
}

/** 一级章节；渲染顺序固定为 paragraphs → list → blocks → footer */
export interface LegalSection {
  title: string
  paragraphs?: string[]
  list?: string[]
  blocks?: LegalBlock[]
  /** 紧跟在 list 之后的收尾段落（例如「违反上述约定的处理」） */
  footer?: string[]
}

export interface LegalDoc {
  key: LegalDocKey
  /** 分段控件上的文字 */
  label: string
  /** 导航栏标题 */
  navTitle: string
  /** 文首导语 */
  intro: string
  sections: LegalSection[]
}

