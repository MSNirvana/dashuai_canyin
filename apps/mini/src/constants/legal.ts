export const LEGAL_DOCS: LegalDoc[] = [USER_AGREEMENT, PRIVACY_POLICY]

/** 路由参数非法时回落到用户协议（不能抛错，否则协议入口点进去直接白屏） */
export function legalDocOf(key?: string): LegalDoc {
  return key === 'privacy' ? PRIVACY_POLICY : USER_AGREEMENT
}
