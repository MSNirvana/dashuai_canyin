-- 记录每次出片**实际用到的配乐文件**，供「同一门店避开最近用过的曲子」派发时参考。
--
-- 背景：配乐此前每次都是**独立随机**抽取，没有任何「这家店最近用过什么」的记忆 ⇒
-- 池子越大也救不了「同一个门店连着几条片子配同一首曲子」（这是生日问题，见
-- `bgm-library.ts::BGM_POOL_TARGET` 那段）。要让运行期能避开最近用过的，就必须先记住用过什么。
--
-- ★ 为什么是独立列而不是塞进 params_json：`storeChatCutState` 对 `params_json` 做**整体替换**，
--   塞进去会被静默冲掉（与租约那几列当年落列的理由相同）。
--
-- 存量数据全部为 NULL（历史任务从未记录过配乐）⇒ 老的判定与查询完全不受影响；
-- 派发时「查不到历史」等价于「没有可避开的」，退化成本次改动之前的随机/轮转行为。
ALTER TABLE `render_task`
  ADD COLUMN `bgm_track` VARCHAR(512) NULL AFTER `cost_ms`;
