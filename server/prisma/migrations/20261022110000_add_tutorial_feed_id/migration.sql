-- 小程序「参考视频」从**内嵌播放器**改为**跳转视频号播放**（2026-10-22）。
--
-- ── 为什么要改，以及为什么是这条路 ──────────────────────────────────────────
-- 1) 腾讯审核按这一页的形态判了「涉及提供播放、观看等服务，请补充选择：文娱-其他视频类目」，
--    该类目要 6 选 1 资质（信息网络传播视听节目许可证等）。
--    判的是**页面形态**，不是组件 —— 换组件不解决问题。
-- 2) 换成官方的 `<channel-video>` 内嵌也走不通：本项目视频号是**个人未认证**，
--    官方社区口径是「视频号没有认证 ⇒ 没有主体」「企业认证前都属个人账号非企业账号」。
--    而内嵌要求「小程序绑定开放平台 + 同/关联主体 + 关联主体列表含视频号主体」，
--    个人视频号进不了企业的关联主体列表 ⇒ 组件这条路在视频号侧就断了。
-- 3) 只剩 `wx.openChannelsActivity`：官方文档明确「跳转打开视频号视频：无主体限制」。
--
-- ── 两列各自的语义，别混 ────────────────────────────────────────────────────
--   feed_id          = 视频号视频的唯一标识（视频号助手 →「动态管理」复制）。
--                      ★★ **这是可见性判据**：为空 ⇒ 这条不下发给小程序。
--                         原来是看 `video_key`，现在 `video_key` 只作历史留存，不参与任何判断。
--   finder_user_name = 视频号 ID（sph 开头）。可为空 ⇒ 服务端用 env
--                      `TUTORIAL_FINDER_USER_NAME` 兜底（只有一个视频号时不必逐行填）。
--
-- ★ 存量数据：`tutorial_video` 在线上是 **0 行**，所以这次改动不需要任何回填；
--   两列都可空，`video_key`/`cover_key` 与上传通道一并保留（封面上传仍在用同一个端点）。
ALTER TABLE `tutorial_video`
  ADD COLUMN `feed_id` VARCHAR(128) NULL AFTER `cover_key`,
  ADD COLUMN `finder_user_name` VARCHAR(64) NULL AFTER `feed_id`;
