-- 素材口播探针的结论：这条素材里**哪几段真的有人在说话**（素材绝对坐标的保留区间列表）。
--
-- 背景：AI 剪辑从来不删「废片」。实测一条 19.48s 的口播素材里有 **11.06s 是空白**
-- （头 1.55s、尾 0.76s、中间 4 处 1.65~2.95s 的长停顿），全部被原样保留进了成片。
-- 根因是**没有任何一步在按「有没有人在说话」裁画面** —— 已有的 `silencedetect` 探针
-- 只跑在 TTS 配音轨上，而且在这类手机直录素材上（底噪 -16dB、峰值已削顶）
-- 连 -40dB 都测不出静音段，判据必须换成**词级时间戳**（腾讯云 ASR `WordInfo: 1`）。
--
-- ★★ 为什么结论必须**落库**，而不是每次合成现算：
--   ① 现算 = 每次重合成都多花一次 ASR 调用；
--   ② 更严重的是**不稳定** —— 同一素材两次识别的词边界可能差几十毫秒，于是
--      「只改调色重合成」（10 积分那档）会把剪辑点也一起改掉，而用户预期只变颜色。
--
-- ★ 三态语义，别把它压成两态（`render/shot-speech.ts` 与 `render/speech-range.ts` 依赖它）：
--     NULL               = **还没探测过**（要用时去探，探完写回）
--     {"ranges": []}     = 探测过、结论是「没什么可剪的」（不要再去探，白花 ASR）
--     {"ranges": [...]}  = 探测过、按这些区间保留
--   ★ 且带 `pauseMs`/`padMs` 参数指纹：阈值一变旧结论自动失效，
--     否则会出现「改了阈值但线上剪法一点变化都没有」这种要查半天的问题。
--
-- ★ 存量数据全部为 NULL ⇒ 行为与本次改动之前**完全一致**（不裁），
--   第一次合成时才会去探一次并写回。因此这次上线不需要任何数据回填。
ALTER TABLE `shot`
  ADD COLUMN `keep_ranges` JSON NULL AFTER `trim_end_ms`;
