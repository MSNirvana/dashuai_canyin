-- 创作内容模式：把「流量款」从四款文案里拆成独立功能后，用来区分两种输入。
--
-- `DISH`（默认）= 菜品驱动：选门店（+可选菜品），四款里除流量款外可选。
-- `TOPIC`       = 话题驱动：不选门店、不选菜品，靠节气/节日/时令话题出稿。
--
-- ★ 为什么必须单独加一列，而不是靠「track='TRAFFIC' 且 dish_id IS NULL」推断：
--   那个组合在**存量数据里本来就存在**（老用户建过没选菜品的流量款创作），
--   推断会把它们全部误判成话题稿，而这两者的提示词完全不同（话题稿不喂门店/菜品）。
--   另外「不选菜品」本身也允许出现在菜品驱动里（只靠门店也能出稿），所以 dish_id 为空
--   不足以表达模式。
--
-- ★ 为什么不直接删掉 `track='TRAFFIC'` 而是加模式位：拍摄页/合成/素材归属都挂在 creation 上，
--   话题稿要能继续拍成片就必须仍是 creation 行；track 保留是为了让下游（如分镜口径）不必改。
--
-- 存量数据：全部自动落到 mode='DISH'（默认值兜住）⇒ 这次迁移对已有创作是**纯加列**，
-- 不改变任何一行已有数据的语义。
ALTER TABLE `creation` ADD COLUMN `mode` VARCHAR(16) NOT NULL DEFAULT 'DISH';

-- 话题稿用的城市（可选）。存**当次生成的快照**，不是指向门店再实时取：
-- 话题稿刻意不绑门店，让它去读门店档案等于把门店又偷偷接回来；而且门店城市随时可改，
-- 读实时值会让「同一条稿重新生成」结果不可复现。空 = 不带城市。
-- 存量数据一律 NULL（不做任何回填）——历史创作都不是话题稿，没有该字段的语义。
ALTER TABLE `creation` ADD COLUMN `topic_city` VARCHAR(64) NULL;

