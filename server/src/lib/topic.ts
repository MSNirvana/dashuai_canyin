// 「今天该蹭什么话题」—— 流量款（话题驱动）专用的提示词变量。
//
// 背景：流量款已从「四款文案」里拆成独立功能（Creation.mode='TOPIC'）：不选门店、不选菜品，
// 只靠「当下节点 + 时令 + 生活共识」起头。这个文件负责把「今天」翻译成**可以直接开口说的话**。
//
// 三条设计判据，都是这一步才想明白的：
//
//   1. ★ **话题方向必须写成「能当第一句话用」的口语句，不能写成标签。**
//      写「亲情 / 团圆 / 时令」等于没写 —— 模型拿到标签只会写回「中秋佳节，阖家团圆」这种播报腔，
//      而这次改动的全部目的就是消灭播报腔。所以这里每一条都是「中秋回不回家、跟谁过」这种
//      具体到能直接念出来的句子。
//
//   2. ★ **必须轮转，否则一个月里每天都是同一个话题。**
//      中秋前两周如果每天都把「中秋」放第一条，用户连着生成三条就全是中秋。所以：
//      · 节点方向按「离得最近的两个节点」取，且**只取 14 天内的**（太远的节点不该抢话头）
//      · 时令方向与生活方向都按**当天序号取模轮转**，同一天稳定、隔天就换
//      判据：同一天调两次结果必须完全一致（不能引入随机数 —— 重生成时用户会以为变了）。
//
//   3. ★ **时事新闻拿不到，就别假装能拿到。**
//      「结合当下时事热点」这件事，服务端没有任何新闻源。硬写「结合最新热点」只会让模型
//      编造明星/事件/政策（它训练数据里的老新闻它会当新的说）。所以：
//      · 可用因子 = 日期能推出来的（节气/节日/季节/时令）+ 与日期无关的生活共识话题
//      · 提示词里**明写禁止编造新闻、热搜、明星、政策**，并给出「拿不准就回到上面几条」的退路
//
// 精度与边界：节点计算全部复用 lib/festival.ts（节气公式、农历表、时区都在那边，
// 这里**不重复实现**，否则两份农历表迟早会漂移）。

