/** 只取 14 天内的节点抢话头；更远的节点（如 11 天后的国庆）不该天天占头条 */
const NODE_WINDOW_DAYS = 14

/** 几个方向一起给。太多模型会挑花眼，太少就总是同一句 */
const MAX_DIRECTIONS = 4

/** 北京时间的「天序号」，用于按天轮转 */
function dayIndex(now: Date): number {
  const { year, month, day } = shanghaiYmd(now)
  return Math.floor(Date.UTC(year, month - 1, day) / 86_400_000)
}

/** 从数组里按天轮转取 n 个（同一天稳定、隔天就换） */
function rotate<T>(arr: readonly T[], n: number, seed: number): T[] {
  if (arr.length === 0) return []
  const out: T[] = []
  for (let i = 0; i < Math.min(n, arr.length); i++) {
    out.push(arr[(seed + i) % arr.length]!)
  }
  return out
}

function seasonOf(month: number): string {
  if (month >= 3 && month <= 5) return '春季'
  if (month >= 6 && month <= 8) return '夏季'
  if (month >= 9 && month <= 11) return '秋季'
  return '冬季'
}

/**
 * 今天可用的起头方向（已去重、已按天轮转）。
 * 导出是为了让契约测试能逐条断言，不必去解析渲染后的文本。
 */
export function topicDirections(now: Date = new Date()): string[] {
  const { month } = shanghaiYmd(now)
  const seed = dayIndex(now)
  const out: string[] = []

  // ① 最近的节点（≤14 天）：最多两个节点、每个节点取 1 条
  const nodes = upcomingNodes(now).filter((n) => n.ahead <= NODE_WINDOW_DAYS).slice(0, 2)
  for (const n of nodes) {
    const list = NODE_TOPICS[n.name]
    if (!list || list.length === 0) continue
    out.push(list[seed % list.length]!)
  }

  // ② 时令
  out.push(...rotate(SEASON_TOPICS[seasonOf(month)] ?? [], 1, seed))

  // ③ 生活共识（至少给两条，保证节点/时令都不合适时还有话可说）
  out.push(...rotate(EVERGREEN_TOPICS, // 组按天换
    Math.max(1, MAX_DIRECTIONS - out.length),
    seed,
  ).map((g) => g[(seed >> 3) % g.length]!))
  // 上面把「组」按天轮转、再在组内按天轮转，这样同一组话题不会连续几天都出来。
  // 用 `seed >> 3` 而不是同一个 seed：两个维度用同一个种子会退化成固定搭配。

  // 去重后截断（节点方向可能与时令撞句）
  return [...new Set(out)].slice(0, MAX_DIRECTIONS)
}

/**
 * 渲染成给提示词用的文本。**保证非空**。
 *
 * 样例（2026-09-20，带城市「廊坊」）：
 * ```
 * 今天是 2026-09-20（星期日），秋季
 * 临近节点：9月23日 秋分（3 天后）；9月25日 中秋节（5 天后）；10月1日 国庆节（11 天后）
 * 这次可以用的起头方向（挑一条写，不要四条都用上）：
 * 1. 中秋回不回家，跟谁过
 * 2. 天凉了，就想吃点热乎的
 * 3. 你是哪儿人，多久没吃到家乡那一口了
 * 4. 加班到几点，晚饭都是怎么解决的
 * 城市：廊坊（可以写「咱廊坊的」这类同城共鸣，但不要编造具体街道或事件）
 * ★ 不要编造新闻、热搜、明星、政策；拿不准就写上面这几条
 * ```
 */
export function formatTopicInfo(now: Date = new Date(), city = ''): string {
  const dirs = topicDirections(now)
  const lines: string[] = [formatDateInfo(now)]

  lines.push('这次可以用的起头方向（挑一条写，不要几条都用上）：')
  dirs.forEach((d, i) => lines.push(`${i + 1}. ${d}`))

  if (city.trim()) {
    lines.push(`城市：${city.trim()}（可以写「咱${city.trim()}的」这类同城共鸣，但不要编造具体街道、店名或事件）`)
  }
  lines.push('★ 不要编造新闻、热搜、明星、政策；拿不准就写上面这几条')
  return lines.join('\n')
}
