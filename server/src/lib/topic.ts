// 「今天该蹭什么话题」—— 流量款（话题驱动）专用的提示词变量。
//
// 背景：流量款已从「四款文案」里拆成独立功能（Creation.mode='TOPIC'）：不选门店、不选菜品，
// 只靠「当下节点 + 时令 + 生活共识」起头。这个文件负责把「今天」翻译成**可以直接开口说的话**。
//
// 五条设计判据，前三条是 2026-09-20 定的，后两条是 2026-10-12 按用户反馈补的：
//
//   1. ★ **话题方向必须写成「能当第一句话用」的口语句，不能写成标签。**
//      写「亲情 / 团圆 / 时令」等于没写 —— 模型拿到标签只会写回「中秋佳节，阖家团圆」这种播报腔，
//      而这一档的全部目的就是消灭播报腔。所以这里每一条都是「中秋回不回家、跟谁过」这种
//      具体到能直接念出来的句子。
//
//   2. ★★ **方向按「主题族」组织，同一天给出的几条必须来自不同的族。**
//      判据（可验收）：`topicDirections()` 的返回值里，任意两条不属于同一族。
//
//   3. ★★★ **同一个自然日里，不同创作要拿到不同的方向组。**
//      `variant` 参数（由创作编号派生）就是为此存在的：
//        · 同一条创作重新生成 → variant 不变 → 结果**完全一致**（重生成时用户不会以为内容变了）；
//        · 不同创作 → variant 不同 → 方向组错开。
//      ⚠ 别把 variant 换成 `Math.random()`：那会让「同一条稿子重生成」也漂移，
//        而这条稿子的文案是**已经扣过积分**的，用户重生成时看到方向变了会以为系统出问题。
//
//   4. ★ **时事新闻与当天天气都拿不到，就别假装能拿到。**
//      这两件事服务端都没有数据源。硬写「结合最新热点」只会让模型编造明星/事件/政策
//      （它训练数据里的老新闻它会当新的说）；硬写「今天降温了」则是把天气也编了。所以：
//        · 可用因子 = 日期能推出来的（节气/节日/季节）+ 与日期无关的生活共识话题；
//        · 「天气」只写**不依赖真实天气**的天气感（「这种忽冷忽热的天气，出门都不知道穿啥」），
//          **绝不报「今天下雨 / 今天几度」** —— 那是编的。全天下的天气都编不得，
//          因为门店在哪、今天什么天，服务端一个字都不知道。
//        · 提示词里明写禁止编造新闻、热搜、明星、政策，并给出「拿不准就回到上面几条」的退路。
//
//   5. ★ **某一族在库里写着、却永远进不了提示词，是最坏的一种缺陷。**
//      原实现里 `EVERGREEN_TOPICS` 有一层 `!/(家乡|老家|老乡|方言|暗号)/` 过滤
//      （本意是别和第 1 条地域身份线撞车），副作用是**「方言暗号」整族 6 条从来没出现过**。
//      现在这一族独立成族、单独轮转，不再经过任何按词的过滤 —— 过滤只按**族**做。
//
// 精度与边界：节点计算全部复用 lib/festival.ts（节气公式、农历表、时区都在那边，
// 这里**不重复实现**，否则两份农历表迟早会漂移）。

